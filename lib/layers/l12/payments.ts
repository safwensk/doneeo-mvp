/**
 * The idempotency key for a PSP callback.
 *
 * Built from what the PSP tells us, so two deliveries of one event produce one
 * key. Nothing here uses a timestamp, a counter or a random value — all three
 * would make a replay look new, which is the entire failure mode.
 */
export function callbackKey(input: {
  pspEventId: string;
  jobOrderId: string;
  kind: PaymentCommand["kind"];
}): string {
  return `${input.kind}-${input.jobOrderId}-${input.pspEventId}`;
}

/**
 * Whether this effect has already been recorded.
 *
 * Intended as a cheap pre-check, NOT as the guarantee. The guarantee is that
 * transactionId is derived from the idempotency key and the ledger store
 * enforces uniqueness on it — so two concurrent replays that both pass this
 * check still produce exactly one posting.
 */
export function alreadyApplied(
  posted: readonly LedgerTransaction[],
  idempotencyKey: string,
): boolean {
  return posted.some(t => t.transactionId === `TXN-${idempotencyKey}`);
}
